interface LanguageContextType {
  currentLanguage: SupportedLanguage;
  setLanguage: (lang: SupportedLanguage) => void;
  t: (key: string, fallback?: string) => string;
  options: LanguageOption[];
}

const LanguageContext = createContext<LanguageContextType>({
  currentLanguage: "en",
  setLanguage: () => {},
  t: (key: string, fallback?: string) => fallback || key,
  options: SUPPORTED_LANGUAGES,
});

export const LanguageProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [currentLanguage, setCurrentLanguage] = useState<SupportedLanguage>("en");

  useEffect(() => {
    try {
      const saved = localStorage.getItem("skilltrack_language") || localStorage.getItem("skillprax_preferred_lang");
      if (saved && SUPPORTED_LANGUAGES.some((l) => l.code === saved)) {
        setCurrentLanguage(saved as SupportedLanguage);
      }
    } catch (_) {}
  }, []);

  const setLanguage = (lang: SupportedLanguage) => {
    setCurrentLanguage(lang);
    try {
      localStorage.setItem("skilltrack_language", lang);
      localStorage.setItem("skillprax_preferred_lang", lang);
      // Sync with user profile on backend asynchronously if user is logged in
      fetch("/api/user/profile", {
        method: "PATCH",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ preferredLanguage: lang }),
      }).catch(() => {});
    } catch (_) {}
  };

  const t = (key: string, fallback?: string): string => {
    const langDict = UI_DICTIONARY[currentLanguage];
    if (langDict && langDict[key]) return langDict[key];
    const enDict = UI_DICTIONARY.en;
    if (enDict && enDict[key]) return enDict[key];
    return fallback || key;
  };

  return (
    <LanguageContext.Provider value={{ currentLanguage, setLanguage, t, options: SUPPORTED_LANGUAGES }}>
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = () => useContext(LanguageContext);

export default LanguageContext;
